"""st07: 균등 사전이 모수의 표현에 달린다(피셔 1922의 요지). 10번 중 7번 성공.
A: p에 균등 → 사후 Beta(8,4). B: sinθ=2p-1인 θ에 균등(-π/2~π/2) → p의 사전은 Beta(1/2,1/2) → 사후 Beta(7.5,3.5).
C: 로그 오즈 log(p/(1-p))에 '균등'(부적절) → 사후 Beta(7,3). 최대가능도는 세 경우 모두 0.7로 같다."""
from scipy import stats
for name, a, b in [('p에 균등', 8, 4), ('θ(sinθ=2p−1)에 균등', 7.5, 3.5), ('로그 오즈에 균등', 7, 3)]:
    d = stats.beta(a, b)
    lo, hi = d.ppf([0.025, 0.975])
    print(f'{name:16} 사후 평균 {d.mean():.3f}  최빈값 {(a-1)/(a+b-2):.3f}  P(p>0.5) {1-d.cdf(0.5):.3f}  95% 구간 {lo:.3f}–{hi:.3f}')
print('1000번 중 700번:')
for name, a, b in [('p에 균등', 701, 301), ('θ에 균등', 700.5, 300.5), ('로그 오즈에 균등', 700, 300)]:
    d = stats.beta(a, b); lo, hi = d.ppf([0.025, 0.975]); print(f'  {name:10} 평균 {d.mean():.4f}  95% {lo:.3f}–{hi:.3f}')

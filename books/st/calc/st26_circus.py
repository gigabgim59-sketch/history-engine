"""st26: 바수(1971)의 서커스 코끼리를 이 책이 고른 수로 다시 셈한다(몸무게는 설명용 가상값).
코끼리 50마리, 3년 전 몸무게로 보아 '삼보'가 평균 몸무게. 설계: 삼보를 99/100, 나머지 49마리를 각각 1/4900의 확률로 뽑는다.
호비츠–톰슨 추정 = 뽑힌 몸무게 / 뽑힐 확률. 모형 기반 추정 = 50 × 삼보의 몸무게."""
w = [4.0]*48 + [4.2, 6.5]  # 톤, 가상: 보통 코끼리 48마리 4.0, 삼보 4.2, 점보 6.5
sambo, jumbo = 4.2, 6.5
total = sum(w)
print('참 총합', total)
print('삼보가 뽑히면 HT', round(sambo / 0.99, 3), ' 모형', 50 * sambo)
print('점보가 뽑히면 HT', round(jumbo * 4900, 1))
print('보통 코끼리가 뽑히면 HT', round(4.0 * 4900, 1))
# HT의 기댓값 = 참 총합(설계 불편)
E = 0.99 * sambo / 0.99 + sum(x * 4900 / 4900 for x in [4.0]*48 + [6.5])
print('HT 기댓값', round(E, 3))

"""st02 '같은 자료, 다른 셈': n번 모두 성공했을 때 다음 번 성공의 확률.
A(라플라스의 계승 규칙): 성공 확률 p에 균등 사전 → (s+1)/(n+2).
B(결과의 열 하나하나에 같은 확률: 가능한 2^n개 열이 모두 같은 확률) → 다음 번은 언제나 1/2.
C(라플라스의 해돋이): 1,826,213일 연속 → 승산 1,826,214 대 1."""
from fractions import Fraction as F
for n in [1, 5, 10, 100, 1826213]:
    a = F(n + 1, n + 2)
    print(f'n={n:>9,}  A={float(a):.6f}  B=0.5')
n = 1826213
a = F(n + 1, n + 2)
print('해돋이 승산', a / (1 - a))
# 부분 성공: 10번 중 7번
print('10번 중 7번 → A', F(8, 12), float(F(8, 12)))
# 베이즈가 물은 형태: 10번 중 7번 성공, 균등 사전 → 사후 Beta(8,4). p가 두 값 사이에 있을 확률
from scipy import stats
b = stats.beta(8, 4)
print('P(p>0.5)=', round(1 - b.cdf(0.5), 3), ' P(0.5<p<0.9)=', round(b.cdf(0.9) - b.cdf(0.5), 3))

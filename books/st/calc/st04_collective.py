"""st04: 폰 미제스의 콜렉티브와 자리 고르기, 준거 집합.
1) 0101… 교대열: 상대 빈도 1/2이지만 '짝수 번째만 고르기'로 빈도 1이 된다 → 콜렉티브가 아니다.
2) 의사난수열(동전): 같은 자리 고르기 뒤에도 빈도가 1/2 근처에 머문다.
3) 준거 집합: 가상의 보험 자료(이 책이 지어낸 수, 설명용). 한 사람이 속하는 세 집합의 사망률이 다르다."""
import numpy as np
n = 100000
alt = np.arange(n) % 2
print('교대열 전체', alt.mean(), ' 짝수 번째', alt[1::2].mean())
rng = np.random.default_rng(3); coin = rng.integers(0, 2, n)
print('동전열 전체', round(coin.mean(), 4), ' 짝수 번째', round(coin[1::2].mean(), 4), ' 앞이 1인 다음', round(coin[1:][coin[:-1] == 1].mean(), 4))
for k in [10, 100, 1000, 10000, 100000]:
    print(f'  처음 {k:>6}번의 빈도 {coin[:k].mean():.4f}')
# 준거 집합(가상): 60세 남성 10,000명 중 사망 120, 그중 흡연자 2,000명 중 사망 50, 흡연·당뇨 200명 중 사망 9
for name, d, m in [('60세 남성', 120, 10000), ('+흡연', 50, 2000), ('+흡연·당뇨', 9, 200)]:
    print(f'{name:8} {d}/{m} = {d/m:.3f}')
# 공정한 동전에서 n번 관측한 빈도가 95%로 놓이는 범위(정규 근사 ±1.96*sqrt(0.25/n))
for k in [10, 100, 1000, 10000, 100000]:
    h = 1.96 * (0.25 / k) ** 0.5
    print(f'  n={k:>6}: 0.5±{h:.4f}')

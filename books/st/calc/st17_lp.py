"""st17: 같은 가능도, 다른 p값. 성공 확률 θ의 실험 두 개.
E1: 10번 시행으로 정함, 성공 3번(이항). E2: 성공 3번이 나올 때까지 시행, 10번째에 멈춤(음이항).
가능도는 둘 다 θ^3(1-θ)^7에 비례. H0: θ=1/2 대 θ<1/2의 한쪽 p값과, θ=0.3 대 0.5의 가능도비, 균등 사전의 사후."""
from scipy import stats
p1 = stats.binom.cdf(3, 10, .5)               # 성공 3번 이하
p2 = stats.binom.cdf(2, 9, .5)                # 9번까지 성공 2번 이하 = 10번 이상 걸림
lr = (0.3**3 * 0.7**7) / (0.5**10)
post = stats.beta(4, 8).cdf(0.5)
print(f'이항 p={p1:.4f}  음이항 p={p2:.4f}  가능도비(0.3:0.5)={lr:.2f}  균등 사전 P(θ<1/2)={post:.3f}')

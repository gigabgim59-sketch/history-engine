"""st05: 정합성과 '네덜란드 책'(내기 묶음).
믿음 정도 q(A)=0.6, q(not A)=0.6인 사람은 각 내기(상금 1)를 0.6에 산다 → 무엇이 일어나도 1.2를 내고 1을 받아 0.2를 잃는다.
q(A)=0.3, q(not A)=0.3이면 반대로 판다 → 0.6을 받고 1을 내 0.4를 잃는다.
정합적(q(A)+q(not A)=1)이면 확실한 손실을 만드는 묶음이 없다(두 결과에서 순손익)."""
def net(qA, qn, buy=True):
    s = 1 if buy else -1
    return [s * (1 - qA - qn), s * (1 - qA - qn)]  # A일 때, not A일 때 (산 쪽 기준: 받는 1 - 낸 값)
print('0.6/0.6 사면', net(0.6, 0.6), ' 0.3/0.3 팔면', net(0.3, 0.3, buy=False))
print('0.6/0.4 사면', net(0.6, 0.4))
# 유한 가법성: 자연수 위의 '균등'은 모든 n에 0을 준다. 가산 가법성이면 합 0 ≠ 1, 유한 가법이면 허용.
print('가산 가법이면 합 =', sum(0 for _ in range(10**6)), '(모두 0) ≠ 1')

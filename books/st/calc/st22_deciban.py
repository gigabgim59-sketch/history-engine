"""st22: 튜링·굿의 '증거의 무게' 단위. 베이즈 인자 B의 무게 = 10·log10(B) 데시반. 독립 관측의 무게는 더한다.
예: 한 관측이 가설을 2배 지지하면 약 3.0 데시반. 이런 관측 10개 → 30.1 데시반 = 베이즈 인자 약 1024."""
from math import log10
for b in [2, 10, 1.5]:
    print(f'B={b}: {10*log10(b):.2f} 데시반')
print('2배 지지 관측 10개:', round(10*10*log10(2), 1), '데시반, B=', 2**10)

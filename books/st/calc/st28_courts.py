"""st28: (1) 콜린스 사건: 특징의 결합 확률 p=1/1,200만. 후보 부부가 N쌍이면 '그런 부부가 적어도 한 쌍 있을 때 둘 이상 있을 확률'.
푸아송 근사 λ=Np. 판결 부록은 N=1/p로 놓아 약 41%를 셈했다고 알려져 있다.
(2) 샐리 클라크: 한 가정의 영아 돌연사 확률 1/8,543을 제곱하면 약 7,300만 분의 1. 독립 가정이 성립하지 않으면 틀린다.
(3) 검사의 오류: P(일치|무죄)와 P(무죄|일치)는 다르다. 후보 인구 N명 중 범인 1명, 무죄인 사람이 우연히 일치할 확률 p."""
import math
p = 1/12_000_000
for N in [1_000_000, 12_000_000, 24_000_000]:
    lam = N*p; P = (1 - math.exp(-lam) - lam*math.exp(-lam)) / (1 - math.exp(-lam))
    print(f'N={N:>11,}: λ={lam:.3f}, 둘 이상일 확률 {P:.3f}')

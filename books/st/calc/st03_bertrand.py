"""st03: 베르트랑(1889)의 현. 반지름 1인 원에서 '무작위로' 고른 현이 내접 정삼각형의 변(√3)보다 길 확률.
세 방법을 몬테카를로로 셈하고 닫힌 꼴과 대조한다."""
import numpy as np
rng = np.random.default_rng(7); N = 2_000_000; L = np.sqrt(3)
t1, t2 = rng.uniform(0, 2*np.pi, (2, N)); a = 2*np.abs(np.sin((t1-t2)/2))            # 두 끝점
d = rng.uniform(0, 1, N); b = 2*np.sqrt(1-d**2)                                    # 반지름 위 거리
r = np.sqrt(rng.uniform(0, 1, N)); c = 2*np.sqrt(1-r**2)                           # 원 안의 중점
for name, x, exact in [('두 끝점을 원둘레에서', a, 1/3), ('반지름 위의 거리', b, 1/2), ('중점을 원 안에서', c, 1/4)]:
    print(f'{name:12} 모의 {np.mean(x > L):.4f}  닫힌 꼴 {exact:.4f}')
# 물과 포도주(무차별 원리를 두 변수에): 포도주/물 비율 x가 1/3~3. x에 균등 → P(x≤2)=(2-1/3)/(3-1/3); 1/x에 균등 → P(1/x≥1/2)=(3-1/2)/(3-1/3)
print('x에 균등', (2-1/3)/(3-1/3), ' 1/x에 균등', (3-1/2)/(3-1/3))
